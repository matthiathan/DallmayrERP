create table if not exists public.telemetry_prepaid_balance_state (
  device_id uuid primary key references public.telemetry_devices(id) on delete cascade,
  carrier text not null default 'Vodacom South Africa',
  ussd_code text not null default '*135*500#',
  remaining_bytes bigint,
  balance_text text,
  query_status text not null default 'unknown',
  last_error text,
  checked_at timestamptz,
  received_at timestamptz,
  request_pending boolean not null default false,
  requested_at timestamptz,
  warning_threshold_bytes bigint not null default 104857600,
  critical_threshold_bytes bigint not null default 26214400,
  check_interval_minutes integer not null default 360,
  stale_after_minutes integer not null default 720,
  updated_at timestamptz not null default now(),
  constraint telemetry_prepaid_balance_remaining_nonnegative check (remaining_bytes is null or remaining_bytes >= 0),
  constraint telemetry_prepaid_balance_status_check check (query_status in ('unknown','ok','parse_failed','unsupported','failed')),
  constraint telemetry_prepaid_balance_thresholds_check check (
    critical_threshold_bytes >= 0 and warning_threshold_bytes > critical_threshold_bytes
  ),
  constraint telemetry_prepaid_balance_interval_check check (check_interval_minutes between 15 and 1440),
  constraint telemetry_prepaid_balance_stale_check check (stale_after_minutes between check_interval_minutes and 10080)
);

create table if not exists public.telemetry_prepaid_balance_history (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.telemetry_devices(id) on delete cascade,
  carrier text not null default 'Vodacom South Africa',

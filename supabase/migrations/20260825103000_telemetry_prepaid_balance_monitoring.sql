  balance_text text,
  query_status text not null,
  error_text text,
  checked_at timestamptz not null,
  received_at timestamptz not null default now(),
  constraint telemetry_prepaid_history_remaining_nonnegative check (remaining_bytes is null or remaining_bytes >= 0),
